"""Classical wrist arousal classifiers with participant-grouped calibration."""

from __future__ import annotations

from pathlib import Path
from time import perf_counter

import joblib
import numpy as np
from scipy.optimize import minimize_scalar
from scipy.special import logsumexp, softmax
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import RobustScaler
from sklearn.svm import SVC
from sklearn.utils.class_weight import compute_sample_weight


GRIDS = {
    'logistic': [{'C': 0.1}, {'C': 1.0}],
    'rbf_svm': [{'C': 1.0}, {'C': 10.0}],
    'random_forest': [{'min_samples_leaf': 3}, {'min_samples_leaf': 10}],
    'xgboost': [{'max_depth': 2}, {'max_depth': 4}],
    'lightgbm': [{'num_leaves': 7}, {'num_leaves': 15}],
}


def estimator(name, params, seed):
    if name == 'logistic':
        return LogisticRegression(**params, max_iter=600, random_state=seed)
    if name == 'rbf_svm':
        return SVC(**params, kernel='rbf', gamma='scale', decision_function_shape='ovr')
    if name == 'random_forest':
        return RandomForestClassifier(**params, n_estimators=80, max_features='sqrt', n_jobs=1, random_state=seed)
    if name == 'xgboost':
        from xgboost import XGBClassifier
        return XGBClassifier(**params, n_estimators=80, learning_rate=0.075, tree_method='hist',
                             n_jobs=1, random_state=seed, verbosity=0)
    if name == 'lightgbm':
        from lightgbm import LGBMClassifier
        return LGBMClassifier(**params, n_estimators=80, learning_rate=0.075, n_jobs=1,
                              verbosity=-1, random_state=seed, deterministic=True, force_col_wise=True)
    raise ValueError(f'Unknown classical model {name!r}')


def fit_estimator(name, params, seed, features, labels):
    # Every fitted transform and every class weight comes from this fit partition.
    transformer = make_pipeline(SimpleImputer(strategy='median', keep_empty_features=True), RobustScaler())
    model = estimator(name, params, seed)
    if name == 'logistic' and len(np.unique(labels)) > 2:
        # With few features and up to four classes, an exact Hessian is small.
        # Float64 avoids loss of precision for rare large physiological peaks.
        model.set_params(solver='newton-cholesky')
        features = np.asarray(features, dtype=np.float64)
    model.fit(transformer.fit_transform(features), labels,
              sample_weight=compute_sample_weight(class_weight='balanced', y=labels))
    if name == 'logistic' and np.max(model.n_iter_) >= model.max_iter:
        raise ArithmeticError('Logistic solver reached its iteration cap')
    return transformer, model


def logits(fitted, features):
    transformer, model = fitted
    if isinstance(model, LogisticRegression) and model.solver == 'newton-cholesky':
        features = np.asarray(features, dtype=np.float64)
    transformed = transformer.transform(features)
    if isinstance(model, SVC):
        margin = model.decision_function(transformed)
        if margin.ndim == 1:
            return np.column_stack((-margin / 2.0, margin / 2.0))
        return margin
    # LightGBM uses autogenerated feature names for ndarray input through sklearn.
    if type(model).__name__ == 'LGBMClassifier':
        probabilities = model.booster_.predict(transformed, num_threads=1)
        if probabilities.ndim == 1:
            probabilities = np.column_stack((1 - probabilities, probabilities))
    else:
        probabilities = model.predict_proba(transformed)
    return np.log(np.clip(probabilities, 1e-7, 1.0))


def temperature(inner_logits, inner_labels, subjects):
    # Equal participant weights avoid fitting a longer session's prevalence.
    weights = np.array([1.0 / np.count_nonzero(subjects == subject) for subject in subjects])

    def loss(log_t):
        scaled = inner_logits / np.exp(log_t)
        nll = logsumexp(scaled, axis=1) - scaled[np.arange(len(inner_labels)), inner_labels]
        return np.average(nll, weights=weights)

    optimum = minimize_scalar(loss, bounds=(np.log(0.2), np.log(5.0)), method='bounded')
    return float(np.exp(optimum.x))


def grouped_inner_score(labels, scores, groups):
    prediction = np.argmax(scores, axis=1)
    values = []
    for group in np.unique(groups):
        mask = groups == group
        values.append(f1_score(labels[mask], prediction[mask], average='macro', zero_division=0))
    return float(np.mean(values))


def inner_subjects(ordered, outer):
    position = ordered.index(outer)
    return [ordered[(position + offset) % len(ordered)] for offset in (1, 8)]


def select_hyperparameters(name, seed, data, train, valid):
    x, y, groups = data['F'], data['y'], data['groups']
    evaluations = []
    scores = []
    for params in GRIDS[name]:
        fitted = fit_estimator(name, params, seed, x[train], y[train])
        result = logits(fitted, x[valid])
        scores.append(result)
        evaluations.append(grouped_inner_score(y[valid], result, groups[valid]))
    # Ties always choose the first (lower-capacity) setting.
    index = int(np.argmax(evaluations))
    temp = temperature(scores[index], y[valid], groups[valid])
    return GRIDS[name][index], temp, evaluations[index], evaluations


def predict_windows(bundle, features, feature_names):
    """Score physiological features extracted with the bundle's input contract."""
    if list(feature_names) != bundle['feature_names']:
        raise ValueError('Feature names/order differ from the trained input contract')
    values = np.asarray(features, dtype=np.float64)
    if values.ndim == 1:
        values = values[None, :]
    if values.ndim != 2 or values.shape[1] != len(feature_names):
        raise ValueError('Expected window-by-feature array matching the saved schema')
    return softmax(logits(bundle['fitted'], values) / bundle['temperature'], axis=1)


def benchmark(bundle, example):
    args = (bundle, example[None, :], bundle['feature_names'])
    for _ in range(3):
        predict_windows(*args)
    timings = []
    for _ in range(12):
        begin = perf_counter()
        predict_windows(*args)
        timings.append(1000 * (perf_counter() - begin))
    return float(np.median(timings)), float(np.quantile(timings, 0.95))


def load_bundle(path):
    """Load only a trusted, locally generated joblib bundle."""
    return joblib.load(Path(path))
